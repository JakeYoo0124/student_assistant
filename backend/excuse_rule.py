CLASS_START, CLASS_END = time(9,10) , time(18,0) # 9시 10분 부터 18시 까지가 수업 (9시 수업 시작이지만 9시 10분까진 지각으로 인정X)

def classify(check_in: time | None, check_out: time | None, went_out: bool ) -> str: #classify 함수선언
    if check_in is None:
        return "결석"
    if went_out:
        return "외출"
    if check_in > CLASS_START:
        return "지각"
    if check_out and check_out < CLASS_END:
        return "조퇴"
    return "정상출결"

