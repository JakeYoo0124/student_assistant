@dataclass
class CourseInfo:
    """질병 상한·휴가 계산에 필요한 과정 정보"""
    전체소정훈련일수: int
    전체소정훈련시간: int
    주평균훈련일수: float
    일평균훈련시간: float
    훈련기간_개월: int
    훈련기간_잔여일: int = 0      # 예) 5개월 16일 → 개월=5, 잔여일=16
    고등학생: bool = False
 
 
def round_half_up(x):
    """소수점 첫째자리에서 반올림 """
    return math.floor(x + 0.5)
 
 
def sick_limit(course):
    """질병·입원 출석인정 상한 = 전체 소정훈련일수의 10%"""
    return round_half_up(course.전체소정훈련일수 * 0.1)
 
 
def vacation_limit(course):
    """과정 전체에서 쓸 수 있는 휴가 일수 (월 1일)"""
    if course.고등학생:
        return 0
    if course.주평균훈련일수 < 5 or course.일평균훈련시간 < 6:
        return 0
    if course.훈련기간_개월 >= 6:
        return course.훈련기간_개월
    # 6개월 미만이라도 700시간 이상 + 5개월 16일 이상이면 6개월로 보고 최대 6일
    over_5m16d = (course.훈련기간_개월 > 5 or
                  (course.훈련기간_개월 == 5 and course.훈련기간_잔여일 >= 16))
    if course.전체소정훈련시간 >= 700 and over_5m16d:
        return 6
    return 0
 
 
def missing_docs(required, submitted):
    """제출하지 않은 증빙 서류 목록을 돌려준다."""
    return [doc for doc in required if doc not in submitted]
 
 
def doc_info(서류명):
    """서류 상세 안내 (나중에 AI 설명 버튼의 기본 자료로 사용)"""
    return DOC_GUIDE.get(서류명, "등록된 안내가 없습니다. 운영팀에 문의하세요.")
 
def accrued_vacation(course, 현재_훈련월):
    """지금까지 발생한 휴가 일수 (매월 1일, 과정 전체 한도까지)"""
    return min(현재_훈련월, vacation_limit(course))

def check_excuse(사유, 대상, 제출서류, 신청일수, course=None,
                 사용한_질병일수=0, 사용한_휴가일수=0, 현재_훈련월=1, 증빙_확인=True):
    """공결 신청이 규칙에 맞는지 확인하고 인정일수를 돌려준다.

    증빙_확인=False 이면 서류 검사를 건너뛴다 (승인 후에 증빙을 내는 흐름의 신청 단계용).
    """
    def reject(msg):
        return {"인정": False, "인정일수": 0, "사유": msg}
 
    rule = EXCUSE_RULE.get(사유)
    if rule is None:
        return reject(f"등록되지 않은 사유: {사유}")
    if not rule["인정"]:
        return reject(f"'{사유}'는 출석 인정 사유가 아님")
    if 대상 not in rule["대상"]:
        return reject(f"'{사유}'의 인정 대상이 아님 (가능: {', '.join(rule['대상'])})")
 
    if 증빙_확인:
        required = rule["증빙"][대상] if isinstance(rule["증빙"], dict) else rule["증빙"]
        부족 = missing_docs(required, 제출서류)
        if 부족:
            return reject(f"증빙 부족: {', '.join(부족)}")
 
    # 사유별 최대 인정일수 결정
    최대 = rule["인정일수"]
    if 사유 == "질병,입원" and course:
        최대 = max(sick_limit(course) - 사용한_질병일수, 0)
    elif 사유 == "휴가":
        if course is None:
            return reject("휴가는 과정 정보(CourseInfo)가 있어야 판단 가능")
        if vacation_limit(course) == 0:
            return reject("휴가 부여 대상 과정이 아님")
        남은휴가 = accrued_vacation(course, 현재_훈련월) - 사용한_휴가일수
        if 남은휴가 <= 0:
            return reject("지금까지 발생한 휴가를 모두 사용함")
        최대 = 남은휴가  # 이전 달에 안 쓴 휴가까지 모아서 사용 가능
 
    인정일수 = 신청일수 if 최대 is None else min(신청일수, 최대)
    초과 = 신청일수 - 인정일수
    msg = "인정" if 초과 == 0 else f"인정 (초과 {초과}일은 결석 처리)"
    return {"인정": 인정일수 > 0, "인정일수": 인정일수, "사유": msg}
 
 
